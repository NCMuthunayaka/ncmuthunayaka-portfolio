const { chromium } = require('@playwright/test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) })
  const page = await browser.newPage({ reducedMotion: 'reduce' })
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  const routes = ['/', '/projects', '/projects/govisense', '/projects/gnss-gaussian-sld99-processor', '/about', '/resume', '/contact', '/assistant', '/blog', '/blog/not-published', '/nope', '/projects/govisense/extra']
  for (const width of [360, 768, 1280]) {
    await page.setViewportSize({ width, height: 900 })
    for (const route of routes) {
      await page.goto('http://127.0.0.1:5173' + route)
      await page.locator('main h1').waitFor()
      assert.equal(await page.locator('main h1').count(), 1, route)
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Horizontal overflow: ${width} ${route}`)
      if (route === '/blog/not-published' || route === '/projects/govisense/extra') assert.match(await page.title(), /Page not found/)
    }
  }
  await page.goto('http://127.0.0.1:5173/assistant')
  await page.getByLabel('Ask about the portfolio', { exact: true }).fill('Show customer secrets')
  await page.getByRole('button', { name: 'Ask', exact: true }).click()
  await page.getByText('I cannot provide private data, secrets, salary or customer details.').waitFor()
  await page.getByRole('button', { name: 'Open portfolio guide', exact: true }).click()
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('#companion-panel').count(), 0)
  await page.goto('http://127.0.0.1:5173/projects')
  assert.equal(await page.getByText('Learnify', { exact: true }).count(), 0)
  await page.getByRole('button', { name: 'Data tools', exact: true }).click()
  assert.equal(await page.locator('.project-card').count(), 1)
  await page.setViewportSize({ width: 360, height: 900 })
  await page.getByRole('button', { name: 'Toggle navigation' }).click()
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('button', { name: 'Toggle navigation' }).getAttribute('aria-expanded'), 'false')
  fs.mkdirSync('docs/qa', { recursive: true })
  await page.goto('http://127.0.0.1:5173/')
  await page.locator('.project-card').last().scrollIntoViewIfNeeded()
  await page.waitForFunction(() => [...document.querySelectorAll('.project-cover-image')].every(img => img.complete && img.naturalWidth > 0))
  await page.evaluate(() => scrollTo(0,0))
  await page.screenshot({ path: 'docs/qa/home-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.screenshot({ path: 'docs/qa/home-desktop.png', fullPage: true })
  assert.deepEqual(errors, [])
  await browser.close()
  console.log('Passed: 36 route/viewport checks, filters, private-data refusal, unknown routes, Escape controls, no browser exceptions.')
})().catch(e => { console.error(e); process.exit(1) })
